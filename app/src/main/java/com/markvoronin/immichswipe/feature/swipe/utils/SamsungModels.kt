// Prefix + letters + first three digits, e.g. "SM-G900A" -> "SM-G900", "GT-I9300" -> "GT-I930".
// The trailing characters only encode region/carrier, so the base code identifies the device.
private val SamsungBaseCode = Regex("""^([A-Z]+-[A-Z]+\d{3})""")

/** Returns the marketing name for a Samsung model code (e.g. "SM-G900A" -> "Galaxy S5"), or null if unknown. */
fun samsungModelName(model: String): String? {
    val base = SamsungBaseCode.find(model.trim().uppercase())?.groupValues?.get(1) ?: return null
    return SamsungModels[base]
}

